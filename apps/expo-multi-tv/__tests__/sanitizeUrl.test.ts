import {
  sanitizeMediaUrl,
  DEFAULT_POSTER_FALLBACK,
  DEFAULT_BACKDROP_FALLBACK,
} from '../../../packages/shared-ui/src/utils/sanitizeUrl';

describe('Media URL Sanitization & Fallback Layer', () => {
  it('accepts valid https and http URLs', () => {
    expect(sanitizeMediaUrl('https://commondatastorage.googleapis.com/test.mp4')).toBe(
      'https://commondatastorage.googleapis.com/test.mp4',
    );
    expect(sanitizeMediaUrl('http://example.com/stream.m3u8')).toBe(
      'http://example.com/stream.m3u8',
    );
  });

  it('accepts relative asset paths', () => {
    expect(sanitizeMediaUrl('./assets/poster.png')).toBe('./assets/poster.png');
    expect(sanitizeMediaUrl('/images/backdrop.jpg')).toBe('/images/backdrop.jpg');
    expect(sanitizeMediaUrl('assets/tv_icons/icon.png')).toBe('assets/tv_icons/icon.png');
  });

  it('rejects dangerous protocols (javascript:, data: binary, vbscript:, file:)', () => {
    expect(sanitizeMediaUrl('javascript:alert(1)')).toBeNull();
    expect(sanitizeMediaUrl('vbscript:msgbox')).toBeNull();
    expect(sanitizeMediaUrl('file:///etc/passwd')).toBeNull();
    expect(sanitizeMediaUrl('data:image/png;base64,iVBORw0KGgoAAA...')).toBeNull();
  });

  it('allows safe SVG data URIs generated by CinePilot', () => {
    const safeSvg = 'data:image/svg+xml;utf8,<svg></svg>';
    expect(sanitizeMediaUrl(safeSvg)).toBe(safeSvg);
  });

  it('rejects malformed URLs, empty strings, and non-string inputs', () => {
    expect(sanitizeMediaUrl('')).toBeNull();
    expect(sanitizeMediaUrl('   ')).toBeNull();
    expect(sanitizeMediaUrl('not-a-valid-url-scheme')).toBeNull();
    expect(sanitizeMediaUrl(null)).toBeNull();
    expect(sanitizeMediaUrl(undefined)).toBeNull();
    expect(sanitizeMediaUrl(12345)).toBeNull();
    expect(sanitizeMediaUrl({})).toBeNull();
  });

  it('provides non-empty, valid SVG fallback placeholders', () => {
    expect(DEFAULT_POSTER_FALLBACK).toContain('data:image/svg+xml;utf8,');
    expect(DEFAULT_BACKDROP_FALLBACK).toContain('data:image/svg+xml;utf8,');
    expect(decodeURIComponent(DEFAULT_POSTER_FALLBACK)).toContain('CINEPILOT');
    expect(decodeURIComponent(DEFAULT_BACKDROP_FALLBACK)).toContain('CINEPILOT AI');
  });
});

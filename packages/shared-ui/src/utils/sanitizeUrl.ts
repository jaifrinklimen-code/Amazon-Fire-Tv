/**
 * CinePilot AI - Centralized Media and URL Sanitizer
 * Rejects javascript:, data:, and malformed URI schemes.
 * Enforces valid http: / https: protocols or safe relative asset paths.
 */

export function sanitizeMediaUrl(rawUrl: unknown): string | null {
  if (typeof rawUrl !== 'string' || !rawUrl.trim()) return null;
  const trimmed = rawUrl.trim();

  // Allow relative local asset paths
  if (
    trimmed.startsWith('/') ||
    trimmed.startsWith('./') ||
    trimmed.startsWith('../') ||
    trimmed.startsWith('assets/')
  ) {
    return trimmed;
  }

  // Reject dangerous schemes
  const lower = trimmed.toLowerCase();
  if (
    lower.startsWith('javascript:') ||
    lower.startsWith('vbscript:') ||
    lower.startsWith('file:') ||
    lower.startsWith('blob:')
  ) {
    return null;
  }

  // Allow safe SVG data URIs (generated by CinePilot artwork generator) but reject arbitrary/unbounded data
  if (lower.startsWith('data:image/svg+xml')) {
    return trimmed;
  }

  // Reject all other raw data URIs (e.g. huge inline base64 blobs)
  if (lower.startsWith('data:')) {
    return null;
  }

  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol === 'https:' || parsed.protocol === 'http:') {
      return parsed.href;
    }
  } catch {
    return null;
  }

  return null;
}

